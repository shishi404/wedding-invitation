import {readFile,writeFile,mkdir,stat} from 'node:fs/promises';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {deliveryFiles} from './runtime-delivery.mjs';

// Explicit allowlist: publishing never includes the full model-authoring library.
export async function githubFiles(){
  const files=await deliveryFiles();
  for(const path of ['.gitignore','README.md','package.json','build-browser.mjs',
    'study.js','study-rules.js','study-art.js','preview.mjs','http-compression.mjs',
    'audit-runtime.mjs','runtime-delivery.mjs','github-files.mjs',
    'prepare-http-assets.mjs','build-static-site.mjs','check-study.mjs',
    'check-study-loft.mjs','check-mobile-scene-view.mjs','启动书房预览.cmd'])files.add(path);
  const result=[...files].sort();
  const pages=result.filter(path=>path.endsWith('.html'));
  if(pages.join(',')!=='index.html,invitation.html')throw Error('Only the two main entry pages may be published');
  for(const path of result){
    if(/\.(?:blend\d*|zip|bak)$/i.test(path))throw Error('Authoring backup in upload: '+path);
    if((await stat(new URL(path,import.meta.url))).size>100*1024*1024)throw Error('GitHub file size limit exceeded: '+path);
  }
  return result;
}
if(process.argv[1]&&import.meta.url===pathToFileURL(resolve(process.argv[1])).href){
  const files=await githubFiles();
  if(process.argv.includes('--write-ignore')){
    const text='# Generated by node github-files.mjs --write-ignore.\n# Keep authoring models, backups, demos and QA output local.\n*\n!*/\n'+files.map(path=>'!/'+path).join('\n')+'\n# Isolated verification copies contain their own ignore rules.\n/output/github-cleanup/\n/output/site-release/\n';
    await writeFile(new URL('.gitignore',import.meta.url),text);
  }
  await mkdir(new URL('output/github-cleanup/',import.meta.url),{recursive:true});
  const inventory=await Promise.all(files.map(async path=>({path,bytes:(await stat(new URL(path,import.meta.url))).size})));
  await writeFile(new URL('output/github-cleanup/files.json',import.meta.url),JSON.stringify(inventory,null,2));
  console.log(JSON.stringify({files:files.length,MiB:Math.round(inventory.reduce((sum,f)=>sum+f.bytes,0)/1048576*100)/100,pages:files.filter(path=>path.endsWith('.html'))}));
}
