// Ship a classic-script entry so double-clicked file:// previews can also boot.
// Keep the rules and scene sources modular for editing and rule tests.
import {readFile,writeFile} from 'node:fs/promises';
const rules=(await readFile(new URL('./study-rules.js',import.meta.url),'utf8')).replace(/^export /gm,'');
const game=(await readFile(new URL('./study.js',import.meta.url),'utf8')).replace(/^import[^\n]+\n/,'');
const scene=await readFile(new URL('./study-art.js',import.meta.url),'utf8');
await writeFile(new URL('./study-browser.js',import.meta.url),`// Generated by node build-browser.mjs. Edit the source files, then rebuild.\n(()=>{\n'use strict';\n${rules}\n${game}\n})();\n(()=>{\n'use strict';\n${scene}\n})();\n`);
console.log('Built study-browser.js for HTTP and local-file previews.');

// The two vendored Three modules use only named imports/exports. Wrap their
// existing source as a classic script so file:// previews can render dice too.
// Preserve the original library license headers and original dice implementation.
const core=await readFile(new URL('./vendor/three.core.js',import.meta.url),'utf8');
const three=await readFile(new URL('./vendor/three.module.js',import.meta.url),'utf8');
const properties=list=>list.split(',').map(value=>{
  const [local,publicName]=value.trim().split(/\s+as\s+/);
  return publicName?`${publicName}:${local}`:local;
}).join(',');
const coreExports=core.match(/^export \{([^}]+)\};?\s*$/m);
const threeImports=three.match(/^import \{([^}]+)\} from ['"]\.\/three\.core\.js['"];?\s*$/m);
const threeExports=three.match(/^export \{([^}]+)\};?\s*$/m);
if(!coreExports||!threeImports||!threeExports)throw new Error('Three module structure changed; update the classic dice bundle builder.');
const coreBody=core.replace(coreExports[0],'');
const threeBody=three.replace(threeImports[0],'').replace(/^export \{[^}]+\} from [^\n]+\n/gm,'').replace(threeExports[0],'');
if(/^\s*(import|export)\s/m.test(coreBody+threeBody))throw new Error('Unsupported dependency in classic dice bundle.');
let dice=(await readFile(new URL('./dice.js',import.meta.url),'utf8')).replace(/^import[^\n]+\n/,'');
// Local-file images taint a canvas used for WebGL textures. Embed the same
// reference bytes for that preview mode, while HTTP still loads separate files.
for(const asset of ['dice-engraving-reference.png','dice-old-seal-reference.png','dice-number-reference.png']){
  const bytes=await readFile(new URL(`./${asset}`,import.meta.url));
  dice=dice.replace(`'./${asset}'`,`(location.protocol==='file:'?'data:image/png;base64,${bytes.toString('base64')}':'./${asset}')`);
}
await writeFile(new URL('./dice-browser.js',import.meta.url),`// Generated by node build-browser.mjs. Includes Three.js (MIT); see vendor/THREE-LICENSE.txt.\n(async()=>{\n'use strict';\nconst core=(()=>{\n${coreBody}\nreturn {${properties(coreExports[1])}};\n})();\nconst THREE=(()=>{\nconst {${threeImports[1]}}=core;\n${threeBody}\nreturn Object.assign({},core,{${properties(threeExports[1])}});\n})();\n${dice}\n})();\n`);
console.log('Built dice-browser.js with the original 3D dice for HTTP and local files.');
